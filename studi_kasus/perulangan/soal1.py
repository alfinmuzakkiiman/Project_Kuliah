# ========================================================
# Studi Kasus 1 - Perulangan / Iteration
# Kasus: Menampilkan Angka 1 Sampai 10
# IPO (Input - Process - Output):
# - Input   : Tidak membutuhkan input pengguna
# - Process : Perulangan for dengan rentang range(1, 11)
# - Output  : Angka 1, 2, 3, ..., 10
# ========================================================

print("=== MENAMPILKAN ANGKA 1 SAMPAI 10 ===")

# Process & Output
for i in range(1, 11):
    print(f"Angka ke-{i}: {i}")

print("\nPerulangan selesai.")
